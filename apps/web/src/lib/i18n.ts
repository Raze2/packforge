const DICTS: Record<Locale, Dict> = { en, fr, ar };

export function isLocale(s: string | null | undefined): s is Locale {
  return s === 'en' || s === 'fr' || s === 'ar';
}

export function dirOf(l: Locale): 'ltr' | 'rtl' {
  return LOCALES.find((x) => x.id === l)?.dir ?? 'ltr';
}

/** Translates `key`; returns `fallback` (or the key) when no dictionary has it. */
export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
  fallback?: string,
): string {
  let s = DICTS[locale][key] ?? en[key] ?? fallback ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}
